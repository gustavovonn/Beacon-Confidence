#ifndef GEODESY_H_
#define GEODESY_H_

#include "Constants.h"
#include "CoordinatePolicies.h"
#include <cmath>

namespace artery {

struct GeoPoint {
    double lat = 0.0;  ///< [deg]
    double lon = 0.0;  ///< [deg]
};

/// Metric displacement in a local East-North tangent plane [m].
struct LocalPoint {
    double east = 0.0;
    double north = 0.0;
};

namespace Geodesy {

/// Displacement of `p` relative to `origin` on the local tangent plane (WGS-84 radii at origin).
inline LocalPoint toLocal(const GeoPoint& origin, const GeoPoint& p)
{
    const double latRad = origin.lat * ConstantsWGS84::DEG_TO_RAD;
    LocalPoint d;
    d.north = (p.lat - origin.lat) * ConstantsWGS84::DEG_TO_RAD * ConstantsWGS84::meridionalRadius(latRad);
    d.east = (p.lon - origin.lon) * ConstantsWGS84::DEG_TO_RAD *
             ConstantsWGS84::primeVerticalRadius(latRad) * std::cos(latRad);
    return d;
}

/// Inverse of toLocal.
inline GeoPoint fromLocal(const GeoPoint& origin, const LocalPoint& d)
{
    const double latRad = origin.lat * ConstantsWGS84::DEG_TO_RAD;
    GeoPoint p;
    p.lat = origin.lat + d.north / ConstantsWGS84::meridionalRadius(latRad) * ConstantsWGS84::RAD_TO_DEG;
    p.lon = origin.lon + d.east / (ConstantsWGS84::primeVerticalRadius(latRad) * std::cos(latRad)) *
                             ConstantsWGS84::RAD_TO_DEG;
    return p;
}

inline double distance(const GeoPoint& a, const GeoPoint& b)
{
    return Wgs84CoordinatePolicy::distance(a.lat, a.lon, b.lat, b.lon);
}

inline double norm(const LocalPoint& d)
{
    return std::hypot(d.east, d.north);
}

/// Wraps an angle to [0, 360).
inline double wrap360(double deg)
{
    deg = std::fmod(deg, 360.0);
    return deg < 0.0 ? deg + 360.0 : deg;
}

/// Wraps an angle to [-180, 180).
inline double wrap180(double deg)
{
    return wrap360(deg + 180.0) - 180.0;
}

/// Bearing of a local displacement, clockwise from north [deg, 0..360).
inline double bearing(const LocalPoint& d)
{
    return wrap360(std::atan2(d.east, d.north) * ConstantsWGS84::RAD_TO_DEG);
}

/// Unit-free direction vector for a heading measured clockwise from north.
inline LocalPoint direction(double headingDeg, double length = 1.0)
{
    const double h = headingDeg * ConstantsWGS84::DEG_TO_RAD;
    return LocalPoint{length * std::sin(h), length * std::cos(h)};
}

/// Rotates a displacement clockwise by `deg` (a vector with bearing b ends up with bearing b + deg).
inline LocalPoint rotateClockwise(const LocalPoint& d, double deg)
{
    const double r = deg * ConstantsWGS84::DEG_TO_RAD;
    const double c = std::cos(r);
    const double s = std::sin(r);
    return LocalPoint{d.east * c + d.north * s, -d.east * s + d.north * c};
}

/// Point reached from `p` after moving `forward` metres along `headingDeg` and `right` metres to its right.
inline GeoPoint offset(const GeoPoint& p, double headingDeg, double forward, double right = 0.0)
{
    const LocalPoint f = direction(headingDeg, forward);
    const LocalPoint r = direction(headingDeg + 90.0, right);
    return fromLocal(p, LocalPoint{f.east + r.east, f.north + r.north});
}

/// Constant-velocity projection of a point over `dt` seconds.
inline GeoPoint project(const GeoPoint& p, double speed, double headingDeg, double dt)
{
    return offset(p, headingDeg, speed * dt);
}

}  // namespace Geodesy

/**
 * @brief Relation between a simulator's projected grid and the true local tangent plane.
 *
 * SUMO networks are projected (e.g. UTM), so grid north differs from true north by the
 * meridian convergence (about -2.2 deg in LuST) and grid metres carry a small scale factor.
 * Artery positions are grid coordinates with +x east and +y SOUTH, and Artery headings are
 * measured clockwise from grid north. CPM object offsets generated by Artery are grid deltas.
 */
struct GridFrame {
    double northBearingDeg = 0.0;  ///< true bearing of grid north [deg]
    double scale = 1.0;            ///< true metres per grid metre

    /// Artery grid delta (+x east, +y south) to a true East/North displacement.
    LocalPoint fromArteryDelta(double dx, double dy) const
    {
        const LocalPoint grid{dx * scale, -dy * scale};
        return Geodesy::rotateClockwise(grid, northBearingDeg);
    }

    /// Inverse of fromArteryDelta: returns {dx, dy} in Artery grid metres (+y south).
    LocalPoint toArteryDelta(const LocalPoint& trueEN) const
    {
        const LocalPoint grid = Geodesy::rotateClockwise(trueEN, -northBearingDeg);
        return LocalPoint{grid.east / scale, -grid.north / scale};
    }

    double toTrueHeading(double gridHeadingDeg) const { return Geodesy::wrap360(gridHeadingDeg + northBearingDeg); }
    double toGridHeading(double trueHeadingDeg) const { return Geodesy::wrap360(trueHeadingDeg - northBearingDeg); }
};
}  // namespace artery

#endif  // GEODESY_H_
