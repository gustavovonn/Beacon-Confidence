#ifndef SENSOR_COVERAGE_H_
#define SENSOR_COVERAGE_H_

#include "Geodesy.h"
#include <algorithm>
#include <cmath>
#include <sstream>
#include <stdexcept>
#include <string>
#include <vector>

namespace artery {

/// One sensor cone, mounted `mountForward` metres ahead of the vehicle centre (negative: behind it,
/// e.g. +2.5 for a front-bumper radar of a 5 m car) and rotated by `mountYawDeg` from the heading.
struct SensorSector {
    double range = 0.0;         ///< [m]
    double apertureDeg = 0.0;   ///< full opening angle [deg]
    double mountYawDeg = 0.0;   ///< 0 = forward, 180 = backward
    double mountForward = 0.0;  ///< [m] along the heading from the vehicle centre
};

/**
 * @brief Fixed field-of-view model, identical for every station.
 *
 * CPMs generated by Artery do not carry sensor detection areas, so the receiver assumes
 * every station has the same sensor layout. It must match config/sensors.xml.
 */
class SensorCoverage {
public:
    SensorCoverage() = default;
    explicit SensorCoverage(std::vector<SensorSector> sectors) : m_sectors(std::move(sectors)) {}

    /// Parses "range:aperture:mountYaw[:mountForward]" entries separated by commas,
    /// e.g. "100:50:0:2.5,100:50:180:-2.5" (ITU-R M.2057-1 Radar B at the front and rear bumpers of a 5 m car).
    static SensorCoverage parse(const std::string& spec)
    {
        std::vector<SensorSector> sectors;
        std::stringstream all(spec);
        std::string item;
        while (std::getline(all, item, ',')) {
            if (item.find_first_not_of(" \t") == std::string::npos) {
                continue;
            }
            SensorSector sector;
            char sep1 = 0;
            char sep2 = 0;
            std::stringstream one(item);
            if (!(one >> sector.range >> sep1 >> sector.apertureDeg >> sep2 >> sector.mountYawDeg) ||
                sep1 != ':' || sep2 != ':') {
                throw std::invalid_argument("invalid sensor sector '" + item + "', expected range:aperture:mountYaw[:mountForward]");
            }
            char sep3 = 0;
            if (one >> sep3) {
                if (sep3 != ':' || !(one >> sector.mountForward)) {
                    throw std::invalid_argument("invalid sensor sector '" + item + "', expected range:aperture:mountYaw[:mountForward]");
                }
            }
            sectors.push_back(sector);
        }
        return SensorCoverage(std::move(sectors));
    }

    /**
     * @brief Is the whole disc of `radius` around p inside one cone? Used for negative evidence: a claim whose true
     * position may lie anywhere within its uncertainty disc is only contradicted by a missing detection if the
     * radar would have seen every such position.
     */
    bool coversDisc(const GeoPoint& hostCentre, double hostHeadingDeg, const GeoPoint& p, double radius) const
    {
        const LocalPoint c = Geodesy::toLocal(hostCentre, p);
        for (const SensorSector& sector : m_sectors) {
            const LocalPoint m = Geodesy::direction(hostHeadingDeg, sector.mountForward);
            const LocalPoint d{c.east - m.east, c.north - m.north};
            const double dist = Geodesy::norm(d);
            if (dist <= radius || dist + radius > sector.range) {
                continue;
            }
            const double halfAngle = std::asin(radius / dist) * ConstantsWGS84::RAD_TO_DEG;
            const double offAxis = std::abs(Geodesy::wrap180(Geodesy::bearing(d) - hostHeadingDeg - sector.mountYawDeg));
            if (offAxis + halfAngle <= 0.5 * sector.apertureDeg) {
                return true;
            }
        }
        return false;
    }

    /// Mount point (local metres from the vehicle centre) of the cone that p is most central in: where a
    /// detection of p is measured from.
    LocalPoint mountFor(double hostHeadingDeg, const LocalPoint& p) const
    {
        LocalPoint best{};
        double bestOffAxis = 1e9;
        for (const SensorSector& sector : m_sectors) {
            const LocalPoint m = Geodesy::direction(hostHeadingDeg, sector.mountForward);
            const LocalPoint d{p.east - m.east, p.north - m.north};
            const double offAxis = std::abs(Geodesy::wrap180(Geodesy::bearing(d) - hostHeadingDeg - sector.mountYawDeg));
            if (offAxis < bestOffAxis) {
                bestOffAxis = offAxis;
                best = m;
            }
        }
        return best;
    }

    /// Farthest point any cone reaches from the vehicle centre [m].
    double maxRange() const
    {
        double range = 0.0;
        for (const SensorSector& sector : m_sectors) {
            range = std::max(range, sector.range + std::abs(sector.mountForward));
        }
        return range;
    }

    bool empty() const { return m_sectors.empty(); }
    const std::vector<SensorSector>& sectors() const { return m_sectors; }

private:
    std::vector<SensorSector> m_sectors;
};

}  // namespace artery

#endif  // SENSOR_COVERAGE_H_
